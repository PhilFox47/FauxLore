/**
 * The starter library: the lines every FauxLore install begins with.
 *
 * This file is SEED DATA, not the live library. On boot it is written into the
 * `flavor_texts` table as global rows, and everything afterwards reads from
 * there — which is what lets a line be retired, or a user's own earned lines to
 * sit alongside these under the same rules.
 *
 * Seeding inserts what is missing and never overwrites, so editing this file
 * adds new lines on the next restart without disturbing anything already in the
 * database. Removing a line here does NOT remove it from an existing install;
 * that is a deliberate one-way door, because the database may have been curated
 * since.
 *
 * Three kinds are mixed on purpose:
 *
 *   quote      something said in the work
 *   reference  a thing the work or the medium is recognised by, not a line
 *   joke       what the people who consume it say to each other about it
 *
 * A line with no `source` is a HOUSE LINE — about the medium itself rather than
 * about any one work. Those carry the format's own texture, and they are the
 * ones a brand-new library leans on hardest, so every type keeps a good stock.
 */

export type StarterKind = "quote" | "reference" | "joke";

export interface StarterFlavorText {
  quote: string;
  /** The work it belongs to. Absent for a house line about the medium. */
  source?: string;
  kind: StarterKind;
}

